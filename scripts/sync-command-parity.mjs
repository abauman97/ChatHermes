// The shared gateway's generated parity table bounds our legacy worker support.
// Discovery remains entirely native. Run after reviewing a Hermes pin change.
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const table = readFileSync(
  new URL(".hermes-source/website/docs/developer-guide/gateway-command-parity.md", root),
  "utf8",
);
const names = table.split("\n").flatMap((line) => {
  const match = line.match(/^\| `\/([^`]+)`.*? \| (read|control)[^|]* \|/);
  return match ? [match[1]] : [];
});
if (!names.length) throw new Error("Missing reviewed gateway command parity table");
const target = new URL("src/features/chat/commands/gateway-parity.ts", root);
if (process.argv.includes("--check")) {
  const actual = [...readFileSync(target, "utf8").matchAll(/^  "([^"]+)"/gm)].map(
    (match) => match[1],
  );
  if (JSON.stringify(names) !== JSON.stringify(actual))
    throw new Error("Gateway command parity changed; review and regenerate");
  console.log(`Reviewed gateway command boundary matches ${names.length} upstream entries.`);
} else {
  writeFileSync(
    target,
    `// Generated by scripts/sync-command-parity.mjs from Hermes 2bd378ed's\n// website/docs/developer-guide/gateway-command-parity.md. This is an execution\n// boundary, not discovery: names, descriptions, aliases and extensions come\n// from commands.catalog. Re-review when changing the pinned runtime.\nexport const gatewayCommands = new Set([\n${names.map((name) => `  "${name}",`).join("\n")}\n]);\n`,
  );
}
